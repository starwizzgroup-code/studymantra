const mongoose = require('mongoose')

const Schema = new mongoose.Schema({
    Role: {
        type: String,
        required: true
    },
    name: {
        type: String,
        required: true
    },
    email: {
        type: String,
        required: true,
        unique: true
    },
    phone: {
        type: String,
        required: true,
        unique: true
    },
    password: {
        type: String,
        required: true
    }
})
const Model = mongoose.model('admins', Schema)
module.exports = Model